import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const previewHtml = fs.readFileSync(path.join(root, 'preview/zone13-graybox.html'), 'utf8');
const previewJs = fs.readFileSync(path.join(root, 'preview/zone13-graybox.js'), 'utf8');
const builder = fs.readFileSync(path.join(root, 'tools/build_zone13_graybox.mjs'), 'utf8');
const manifestPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/zone13-graybox.json');
const meshPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/zone13-graybox.bin');
const atlasPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/zone13-material-atlas.png');
const atlasManifestPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/zone13-material-atlas.json');
const navPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/zone13-navmesh.json');
const planPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/zone13-gameplay-plan.json');
const walkPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/zone13-walkmesh.json');
const auditPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/zone13-mobility-audit.json');
const staticModelsPath = path.join(root, 'assets/local/cf_bio_candidates/zone13/graybox/static-models/manifest.json');

assert.match(previewHtml, /Zone 13 · 生化地图隔离灰盒/);
assert.match(previewHtml, /location\.protocol === 'file:'/);
assert.match(previewHtml, /http:\/\/127\.0\.0\.1:8123\/preview\/zone13-graybox\.html/);
assert.match(previewJs, /zone13-isolated-graybox/);
assert.doesNotMatch(previewJs, /scripts\/main\.js|buildLingyinMap|EnemyManager/);
assert.match(builder, /zm_zone13\.bsp/);
assert.ok(fs.existsSync(manifestPath), 'missing generated graybox manifest');
assert.ok(fs.existsSync(meshPath), 'missing generated graybox mesh');
assert.ok(fs.existsSync(atlasPath), 'missing generated material atlas');
assert.ok(fs.existsSync(atlasManifestPath), 'missing material atlas manifest');
assert.ok(fs.existsSync(navPath), 'missing navmesh conversion');
assert.ok(fs.existsSync(planPath), 'missing gameplay plan');
assert.ok(fs.existsSync(walkPath), 'missing walkmesh');
assert.ok(fs.existsSync(auditPath), 'missing mobility audit');
assert.ok(fs.existsSync(staticModelsPath), 'missing converted static models');

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
assert.equal(manifest.format, 'zone13-graybox-v1');
assert.equal(manifest.sourceVersion, 21);
assert.ok(manifest.stats.triangles > 1000);
assert.ok(manifest.stats.materials >= 3 && manifest.stats.materials <= 7);
assert.ok(manifest.groups.some((group) => group.id === 'atlas' && group.vertexCount > 0));
assert.ok(manifest.stats.entities > 100);
assert.ok(manifest.stats.staticProps > 20);
assert.equal(manifest.staticProps.length, manifest.stats.staticProps);
assert.ok(manifest.staticProps.some((prop) => /bus\.mdl$/i.test(prop.model)));
assert.ok(manifest.staticProps.filter((prop) => /bus\.mdl$/i.test(prop.model)).every((prop) => prop.scale > 20), 'Zone13 v11 trailing prop scale must be preserved');
assert.ok(manifest.staticProps.filter((prop) => /car\.mdl$/i.test(prop.model)).every((prop) => prop.size[0] > 5), 'vehicle bounds must stay at world scale');
const atlas = JSON.parse(fs.readFileSync(atlasManifestPath, 'utf8'));
assert.equal(atlas.slots.length, 16);
assert.deepEqual([...fs.readFileSync(atlasPath).subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10]);
const nav = JSON.parse(fs.readFileSync(navPath, 'utf8'));
assert.equal(nav.majorVersion, 16);
assert.equal(nav.stats.areas, 1185);
assert.ok(nav.stats.connections > 1000);
assert.equal(nav.stats.parsedBytes, nav.stats.sourceBytes);
assert.ok(nav.stats.spawnsOnLargestComponent > 0);
const plan = JSON.parse(fs.readFileSync(planPath, 'utf8'));
assert.equal(plan.status, 'preview-only');
assert.equal(plan.rules.source.preparationSeconds, 20);
assert.equal(plan.rules.current.preparationSeconds, 15);
assert.equal(plan.rules.source.weaponCrates, 12);
assert.deepEqual(plan.rules.source.airdropSeconds, [60, 120]);
assert.equal(plan.rules.source.weaponPoolWeighted.length, 7);
assert.equal(plan.reachability.checkedPoints, 32);
assert.equal(plan.reachability.pointsOnMainComponent, 32);
const walk = JSON.parse(fs.readFileSync(walkPath, 'utf8'));
const audit = JSON.parse(fs.readFileSync(auditPath, 'utf8'));
assert.equal(walk.status, 'preview-only');
assert.equal(walk.stats.areas, 1182);
assert.equal(walk.stats.triangles, 2364);
assert.equal(walk.spawnStarts.length, 10);
assert.equal(walk.stats.propColliders, 10);
assert.equal(audit.summary.spawnStarts, 10);
assert.equal(audit.summary.reachableSpawnStarts, 10);
assert.equal(audit.summary.dropTransitions, 9);
assert.equal(audit.summary.offmeshTransitions, 0);
assert.equal(audit.summary.blockedTransitions, 0);
assert.equal(audit.summary.reachableAreas, 1182);
assert.match(previewJs, /zone13-mobility-risks/);
assert.match(previewJs, /cache: 'no-store'/);
const staticModels = JSON.parse(fs.readFileSync(staticModelsPath, 'utf8'));
assert.equal(staticModels.models.length, 7);
assert.ok(staticModels.triangles > 2000);
assert.ok(staticModels.models.every((model) => model.parts.every((part) => part.texture)));
assert.match(previewHtml, /Source 静态模型/);
assert.match(previewHtml, /车辆位置提示/);
assert.match(previewJs, /zone13-vehicle-locators/);
assert.match(previewJs, /worldMeshRoot\.visible = !inspectingProps/);
assert.match(previewHtml, /WASD 行走测试/);
assert.match(previewJs, /createZone13Walkmesh/);
assert.match(previewJs, /createZone13Interactions/);
assert.match(previewJs, /createZone13Round/);
assert.match(previewJs, /createZone13Agents/);
assert.match(previewJs, /createZone13Combat/);
