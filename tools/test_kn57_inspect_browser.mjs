 assert.equal(await page.evaluate(()=>__tactical.admittedView('kn57').clip),'idle_0','reload cancels inspect');
 await page.keyboard.press('v');await page.waitForFunction(()=>__tactical.admittedView('kn57').clip==='inspect');
