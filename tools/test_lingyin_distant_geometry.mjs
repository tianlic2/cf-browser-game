import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from '../lingyin-map/node_modules/typescript/lib/typescript.js';
import * as THREE from '../lingyin-map/node_modules/three/build/three.module.js';
const root=new URL('../',import.meta.url);
const source=await readFile(new URL('lingyin-map/src/world/distant_geometry.ts',root),'utf8');
let js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
js=js.replace(/from ['"]three['"]/,`from '${new URL('lingyin-map/node_modules/three/build/three.module.js',root).href}'`);
const {distantGeometry,configureProjectedLOD}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const original=new THREE.SphereGeometry(2,100,80),positions=original.attributes.position.array.slice();
const far=distantGeometry(original,20),copy=distantGeometry(original,20);
assert.deepEqual(original.attributes.position.array,positions,'near/medium models must stay byte-for-byte unchanged');
assert.ok(far.index.count<original.index.count*.2,'distant mesh must materially reduce triangles');
assert.deepEqual(copy.index.array,far.index.array);assert.deepEqual(copy.attributes.position.array,far.attributes.position.array);
for(let i=0;i<far.index.count;i++)assert.ok(far.index.getX(i)<far.attributes.position.count);
for(const attr of [far.attributes.position,far.attributes.normal])for(const v of attr.array)assert.ok(Number.isFinite(v));
far.computeBoundingBox();assert.ok(far.boundingBox.getSize(new THREE.Vector3()).x>3.8,'preserve overall silhouette');
const skin=original.clone();skin.setAttribute('skinIndex',new THREE.Uint16BufferAttribute(new Uint16Array(positions.length/3*4),4));
assert.throws(()=>distantGeometry(skin),/static/,'never simplify animated actors with this helper');
const lod=new THREE.LOD();lod.addLevel(new THREE.Object3D(),0);lod.addLevel(new THREE.Object3D(),20);lod.addLevel(new THREE.Object3D(),40);
configureProjectedLOD(lod);lod.updateMatrixWorld(true);
const camera=new THREE.PerspectiveCamera(75);camera.position.z=70;camera.updateMatrixWorld(true);lod.update(camera);
assert.equal(lod.getCurrentLevel(),2);
camera.fov=11;lod.update(camera);
assert.equal(lod.getCurrentLevel(),0,'a magnified sniper view must recover near detail');
assert.equal(camera.zoom,1);assert.equal(camera.fov,11);assert.equal(camera.position.z,70,'never mutate the real aim camera');
const hall=await readFile(new URL('lingyin-map/src/world/main_hall_study.ts',root),'utf8');
assert.match(hall,/1\.35, 0, 0, 0\), 20, \.12/,'near scanned Buddha LOD threshold is unchanged');
assert.match(hall,/distantBuddha[^\n]*40,\.12/,'distant tier has hysteresis');
const terrain=await readFile(new URL('lingyin-map/src/world/terrain.ts',root),'utf8');
assert.match(terrain,/if\(buried\)continue/);
const editor=await readFile(new URL('preview/lingyin-editor.js',root),'utf8');
assert.match(editor,/\{editor:true\}/,'editing retains complete terrain when paving is hidden');
console.log('distant geometry passed: deterministic reduction, intact near scans, stable silhouette, actor exclusion, editor terrain retained');
