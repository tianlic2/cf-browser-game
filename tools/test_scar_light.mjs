import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import vm from 'node:vm';
import {SCAR_LIGHT_SELECT_DURATION,SCAR_LIGHT_RELOAD_DURATION,SCAR_LIGHT_FIRE_CLIPS} from '../scripts/scar_light.js';
const root=new URL('../',import.meta.url),read=p=>readFile(new URL(p,root));
const text=async p=>(await read(p)).toString();
const base='assets/local/scar_light/';
const d=JSON.parse(await text(base+'view.json')),manifest=JSON.parse(await text(base+'provenance.json'));
for(const file of Object.keys(manifest.files))assert.deepEqual(await read(base+file),await read('assets/preview/gamebanana-weapons/scar-light/'+file),`reviewed ${file} must remain unchanged`);
assert.equal(d.bones.length,52);assert.equal(d.uvConvention,'classic-smd-v');
assert.ok(d.parts.some(p=>p.additive&&p.effect));
assert.ok(Math.abs(d.clips.select.times.at(-1)-SCAR_LIGHT_SELECT_DURATION)<1e-7);
assert.ok(Math.abs(d.clips.reload.times.at(-1)-SCAR_LIGHT_RELOAD_DURATION)<1e-7);
for(const name of SCAR_LIGHT_FIRE_CLIPS)assert.ok(d.clips[name]?.count>10);
assert.deepEqual(d.events.reload.map(e=>e.frame),[18,39]);assert.equal(d.events.select[0].time,3/30);
const glb=await read(base+'world.glb');assert.equal(glb.toString('ascii',0,4),'glTF');
const world=JSON.parse(glb.toString('utf8',20,20+glb.readUInt32LE(12)));
assert.equal(world.skins,undefined);assert.equal(world.nodes.length,1);
const pos=world.accessors[world.meshes[0].primitives[0].attributes.POSITION];
assert.equal(pos.count/3,2924);assert.ok(Math.abs(pos.max[2]-pos.min[2]-.82)<1e-6);
assert.equal(world.materials[0].name,'QV-ScarLight_S_BaiHu.bmp');
assert.equal(manifest.publicRedistributionApproved,false);
assert.ok(execFileSync('git',['check-ignore',base+'view.json'],{encoding:'utf8'}).trim());
const main=await text('scripts/main.js'),audio=await text('scripts/audio.js'),catalog=await text('scripts/guncatalog.js');
assert.match(main,/const PRIMARY_IDS = \["ak", "m4", "barrett", "scar", "m200", "akgold", "kn57"\]/);
const packs=main.match(/const BACKPACKS = \[([\s\S]*?)\n\];/)[1];
assert.deepEqual([...packs.matchAll(/primary: "([^"]+)"/g)].map(m=>m[1]),['ak','m4','barrett','m4','scar','m200','akgold','kn57']);
assert.match(catalog,/ENEMY_GUN_IDS = \["ak", "m4", "barrett"\]/);
assert.match(main,/trackAsset\(loadScarLightView\(\)/);
assert.match(main,/scarLightView\.root\.visible=false/);
assert.match(main,/cachePlayerMuzzle\(_muzzleLocal,'scar'\)/);
assert.match(audio,/frames=\[18,39\],ids=\["scar_clipout","scar_clipin"\]/);
assert.match(audio,/id:"scar_select",kind:type,delay:3\/30/);
assert.match(audio,/if \(id === "scar"\)[\s\S]*?sample:"scar_fire"/);
const sandbox=vm.createContext({addEventListener(){}});
vm.runInContext(audio.replace('export class SFX','class SFX')+'\nglobalThis.SFX=SFX;',sandbox);
const sfx=Object.create(sandbox.SFX.prototype),played=[];
sfx.ready=()=>true;sfx._playMapped=(method,options)=>played.push({method,...options});
sfx._sample=(id,options)=>{played.push({id,...options});return {};};sfx._note=()=>{};
sfx.shoot('rifle','scar','stock');assert.equal(played.length,1);
assert.equal(played[0].sample,'scar_fire');assert.equal(played[0].rate,1);assert.equal(played[0].wet,0);
played.length=0;sfx.deploy('rifle',{weaponId:'scar'});
assert.equal(played[0].id,'scar_select');assert.equal(played[0].delay,.1);assert.equal(played[0].schedule,'deploy');
played.length=0;sfx.reload({id:'scar',dur:SCAR_LIGHT_RELOAD_DURATION});
assert.deepEqual(played.map(p=>p.id),['scar_clipout','scar_clipin']);
for(const [i,frame] of [18,39].entries()){
 assert.ok(Math.abs(played[i].delay-frame/22)<1e-10);
 assert.equal(played[i].schedule,'reload');assert.equal(played[i].rateJitter,0);
}
for(const id of ['an94','scar-heavy','mp7','tar21','colt1911','dsr1','remington870','striker'])assert.ok(!main.includes(`primary: "${id}"`));
console.log('PASS: BaiHu remains byte-identical with native action timing and an arm-free world model while the two separately approved imports coexist.');
