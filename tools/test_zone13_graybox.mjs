assert.match(previewHtml, /模拟感染一人/);
assert.match(previewHtml, /生化角色与追逐 AI/);
assert.match(previewHtml, /玩家：人类/);
assert.match(previewHtml, /现有 AK 参数射击/);
assert.ok(manifest.markers.some((marker) => marker.kind === 'spawn'));
assert.equal(manifest.markers.filter((marker) => marker.kind === 'weapon').length, 12);
assert.equal(manifest.markers.filter((marker) => marker.kind === 'supply').length, 10);
