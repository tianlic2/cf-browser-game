// ===== 世界 IBL 去蓝：整幅画面「发灰发冷」的真正根因，以及它的**唯一**实现 =====
//
// **这一条是量出来的，不是调出来的。** 用 /tmp/pngpx.mjs 对四个机位截图做像素统计，
// 暖冷指数 (R−B) 分别是 −23 / −31 / −36 / −31 —— 整幅画面在每个机位上都严重偏蓝，
// 而太阳光 (0xfff4e0) 明明是暖的。原因不在配色，在**能量占比**：
//
//   天顶色 `#0d3f86` 转成线性是 (0.0043, 0.0508, 0.2377) —— **B/R ≈ 55**。
//   这张贴图同时是 `scene.background` 与 `scene.environment`，而后者作为 IBL
//   给**每一个** `MeshStandardMaterial` 提供漫反射辐照度：半球积分以天顶权重最大，
//   于是那片极蓝的天顶把整个下半球都染蓝了。
//
// 太阳只在**正对它的那些面**上压得住这层蓝，所以受光面尚可、背光面与地面全是蓝的。
// 单纯调 `PAL.*` 是治不好的 —— 那是拿一个有限的反照率去乘一个无限灌进来的蓝色辐照。
//
// 做法：按金属度分档降 `envMapIntensity`（IBL 的**唯一**总开关）。
//   · 介质（metalness ≤ 0.5）的 IBL 里**漫反射项占绝对多数**，而漫反射项正是蓝色污染的
//     来源 —— 砍到 **0.35** 等于把蓝灌进来的量减掉六成半，天空的直射与半球光原封不动。
//   · 金属（metalness > 0.5）的 IBL **只有镜面项**，那就是金属的本色（AGENTS.md 记过：
//     AWM 金皮 metalness 0.78，没有 IBL 会渲成一块黑铁）。所以它必须保住，只降一档 → **0.85**。
//   · `userData.envLock` 豁免（目前只有舷窗玻璃 —— 它靠反射天空读作玻璃）。
//
// ---------- 这张牌**管多大用**：受控 A/B 实测 ----------
//
// 起因是「掉在甲板上的枪发蓝发平」。当时的**假设**是：枪械材质来自 `guncatalog.js`，
// 是在 `tameWorldEnv(scene)` **之后** 33 行才用 `cloneWithMaterials` 克隆出来的一份，
// **不共享场景里任何材质**，所以从来没被调过、一直吃满未去蓝的 IBL。给 `guncatalog`
// 也接上这一趟之后一量，**假设被证伪**：
//
//   冻结一个掉落物，只翻 `envMapIntensity`（A/B/A，A1/A2 逐像素一致、远处甲板阴性对照 Δ0.00%）：
//
//     envMapIntensity   AK 机匣 Metal met 0.72        AK 枪托 Wood met 0.22
//     1.0（改动前）      rgb(78,95,112) R−B −34  亮 92.6   rgb(141,100,61) R−B +80 亮 105.9
//     0.85（规则·金属档） rgb(74,89,105) R−B −31  亮 87.0   ——（木质走介质档，不适用）
//     0.35              rgb(61,68,75)  R−B −14  亮 67.0   rgb(135,89,47)  R−B +88 亮 95.7
//     0.00（IBL 全关）   rgb(51,49,47)  R−B  −4  亮 49.3   rgb(132,81,37)  R−B +91 亮 88.7
//
// 读出来的三件事，都必须留在这里，否则下一个人会把这条再查一遍：
//   ① **金属档 0.85 相对 1.0 只挪 3 个点**（−34 → −31，亮度 −5.6）。也就是说它能做的
//      几乎等于什么都不做 —— 机匣之所以发蓝**不是因为漏了去蓝**，是它在直射天空下反射天空
//      （金属的镜面项就是天穹的颜色），而**这正是金属该有的样子**。
//   ② 真正把机匣推到中性的是 **0.35 及以下**（−14 / −4），但代价是亮度 92.6 → 67.0，
//      机匣会**比它躺着的甲板还暗**。6 倍放大目视对比，1.0 与规则档两张图**看不出差别**。
//      所以金属档维持 0.85：不为一个看不出来的色偏去牺牲金属的亮度与金属感。
//   ③ 木质枪托的饱和度**与 IBL 基本无关**（R−B 从 +80 走到 +91 而已）—— 那是皮肤自己的
//      木色偏橙（P6 的问题），去蓝治不了它。**别把「木托太橙」记在这条账上。**
//
// 敌人**本体**同样量过（32 个网格、metalness 0.05 / 0.45，同样冻结姿势 A/B/A）：
//     躯干 1.0 → rgb(56,67,59) R−B **−3** 亮 64.1 ｜ 0.35 → rgb(44,49,37) R−B +7 亮 47.1
// 也就是说 **1.0 下敌人本来就已经是中性橄榄绿**（R−B −3），去蓝只会让他们整体暗 26%、
// 而背景是浅褐色木箱 —— 对比度反而更差。所以**敌人本体不打这张牌**（AGENTS.md 那条
// 「已知的不一致」现在有实测支撑了：不是没修，是量过之后决定不修）。
//
// **为什么单独成一个模块**：规则只此一份，名字就是它的把手（`grep tameEnvIntensity`）。
// 将来任何新的材质来源（新道具、新模型、新的程序化几何）都从这里取，不要再写第二个
// 常数 —— 两份常数必然漂移，而且**改一处忘一处不会有任何报错**。
export function tameEnvIntensity(root) {
  const seen = new Set();
  let n = 0;
  root.traverse((o) => {
    const m = o.material;
    if (!m) return;
    for (const mm of Array.isArray(m) ? m : [m]) {
      if (seen.has(mm.uuid) || !mm.isMeshStandardMaterial) continue;
      // 豁免：打 `envLock` 的材质不动。目前只有舷窗玻璃用这张牌 —— 它靠「反射天空」
      // 读作玻璃，砍掉 IBL 就退回一块黑（见 map.js 的 glassMat）。
      if (mm.userData && mm.userData.envLock) continue;
      seen.add(mm.uuid);
      mm.envMapIntensity = (mm.metalness ?? 0) > 0.5 ? 0.85 : 0.35;
      n++;
    }
  });
  return n;
}
